def points(games):
    total = 0
    for game in games:
        x, y = map(int, game.split(':'))
        if x > y:
            total += 3
        elif x == y:
            total += 1
    return total

#Обяснение: Функция points принимает список строк games, каждая из которых представляет результат игры в формате "x:y", где x - количество очков первой команды, а y - количество очков второй команды. Функция подсчитывает общее количество очков для первой команды: 3 очка за победу (x > y), 1 очко за ничью (x == y) и 0 очков за поражение (x < y). Она возвращает суммарное количество очков.

