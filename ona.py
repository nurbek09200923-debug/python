def expression_matter(a, b, c):
    return max(
      a + b + c,
      a * b * c,
      a * (b + c),
      (a + b) * c,
      a + b * c,
      a * b + c,
        )

#Обяснение: Функция expression_matter принимает три целых числа a, b и c, и возвращает максимальное значение, которое можно получить, используя эти числа с различными арифметическими операциями (сложение и умножение) и скобками. Она вычисляет все возможные комбинации выражений и возвращает наибольшее из них.

